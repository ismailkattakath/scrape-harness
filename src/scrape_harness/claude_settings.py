"""The project's .claude/settings.json, GENERATED from pipeline.toml.

A plugin cannot ship permission rules (only `agent` / `subagentStatusLine` survive from a plugin's
settings), so the deny rules that back the plugin's hooks are rendered into each consumer's project
settings from its pipeline, and a test fails when the committed file drifts from the render.

A consumer with a site overlay (pipeline.py site_overlay) keeps its site hosts out of the repo, so the
committed settings.json carries only the generic rules, and the site-host rules render into
.claude/settings.local.json (git-ignored), from the site file.

The rules are a second line only: permission patterns match command TEXT (prefix + wildcards), so the
plugin's hooks stay the real gate. They are worth having because they bind every caller, including
a session where the plugin is not loaded.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import pipeline

# File types that are data, never repo content. The plugin's write hook holds the same set
# (plugin/hooks/guard.py DATA_EXT, stdlib-only); a test asserts the two are equal.
DATA_EXT = (".jsonl", ".ndjson", ".csv", ".tsv", ".parquet", ".sqlite", ".db")
# The ONE marketplace repo (on GitHub); the plugin is its plugins/scrape-harness. The
# marketplace's name is the repo owner, derived here so it is written once.
MARKETPLACE_REPO = "kattakath/skills"
MARKETPLACE_NAME = MARKETPLACE_REPO.split("/")[0]
MARKETPLACE = {"source": {"source": "github", "repo": MARKETPLACE_REPO}}
PLUGIN = f"scrape-harness@{MARKETPLACE_NAME}"
STATUSLINE = Path(".claude") / "statusline.py"
STATUSLINE_COMMAND = 'python3 "${CLAUDE_PROJECT_DIR:-.}/.claude/statusline.py"'


def site_rules(hosts) -> list[str]:
    return [r for host in hosts for r in (f"Bash(curl *{host}*)", f"Bash(wget *{host}*)")]


def render(pl: pipeline.Pipeline | None = None) -> dict:
    pl = pl or pipeline.current()
    if pl.consumer.site_overlay:
        pl = pipeline.load_repo(pl.path)  # the committed file never depends on the site file
    c = pl.consumer
    deny = []
    # Edit(path) only: Claude Code matches file permission checks against Edit rules, which cover every
    # file-editing tool (Write included); a Write(path) rule is inert (2.1.318 warns "is not matched").
    deny += [f"Edit(**/*{ext})" for ext in DATA_EXT]
    deny += ["Edit(./data/**)", "Read(./.env)", "Read(./.env.*)", "Read(./.envrc.local)"]
    if not c.site_overlay:
        deny += site_rules(c.site_hosts)
    deny += [f"Bash(printenv {name})" for name in c.secret_envs]
    deny += ["Bash(git add -f *)", "Bash(git add --force *)"]
    return {
        "$schema": "https://json.schemastore.org/claude-code-settings.json",
        "permissions": {**({"allow": list(pl.claude_allow)} if pl.claude_allow else {}), "deny": deny},
        "env": {"CLAUDE_CODE_ENABLE_TODO_TOOLS": "1"},
        # The live status of the latest run (STATE/status.json); a plugin cannot ship a statusLine.
        # A project-relative launcher, never the CLI by name: in a session without the dev shell, PATH
        # does not find the consumer's CLI (and a short name can collide: `ex` is POSIX vi's editor).
        "statusLine": {"type": "command", "command": STATUSLINE_COMMAND, "refreshInterval": 5},
        "extraKnownMarketplaces": {MARKETPLACE_NAME: MARKETPLACE},
        "enabledPlugins": {PLUGIN: True},
    }


def statusline_text(pl: pipeline.Pipeline | None = None) -> str:
    """The launcher: status.py verbatim (stdlib, Python 3.9) plus the consumer's names, baked in."""
    c = (pl or pipeline.current()).consumer
    src = (Path(__file__).parent / "status.py").read_text()
    return (
        "#!/usr/bin/env python3\n# GENERATED by `<cli> claude-settings --write` from scrape_harness/status.py and "
        "pipeline.toml; do not edit.\n"
        + src
        + f'\n\nif __name__ == "__main__":\n    raise SystemExit(standalone({c.cli!r}, {c.state_env!r}, {c.state_dirname!r}))\n'
    )


def text(pl: pipeline.Pipeline | None = None) -> str:
    return json.dumps(render(pl), indent=2, ensure_ascii=False) + "\n"


def local_text(pl: pipeline.Pipeline | None = None) -> str | None:
    """settings.local.json: the site-host deny rules from the site file; None without a site overlay."""
    pl = pl or pipeline.current()
    if not pl.consumer.site_overlay:
        return None
    doc = {"permissions": {"deny": site_rules(pl.consumer.site_hosts)}}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def local_target(root: Path | None = None) -> Path:
    return target(root).parent / "settings.local.json"


def target(root: Path | None = None) -> Path:
    return (root or pipeline.current().path.parent) / ".claude" / "settings.json"


def check(root: Path | None = None) -> bool:
    p, sl = target(root), target(root).parent.parent / STATUSLINE
    ok = p.is_file() and p.read_text() == text() and sl.is_file() and sl.read_text() == statusline_text()
    if (lt := local_text()) is not None:
        lp = local_target(root)
        ok = ok and lp.is_file() and lp.read_text() == lt
    return ok


def write(root: Path | None = None) -> Path:
    p = target(root)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text())
    sl = p.parent.parent / STATUSLINE
    sl.write_text(statusline_text())
    sl.chmod(0o755)
    if (lt := local_text()) is not None:
        local_target(root).write_text(lt)
    return p
